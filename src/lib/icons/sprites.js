/**
 * Turn a sprite grid into rectangles, merging horizontal runs of the same
 * colour so a 16x16 icon costs a couple of dozen nodes instead of 256.
 * @param {string[]} grid
 * @returns {{x: number, y: number, w: number, fill: string}[]}
 */
export function spriteRects(grid) {
	/** @type {{x: number, y: number, w: number, fill: string}[]} */
	const rects = [];

	grid.forEach((row, y) => {
		let x = 0;
		while (x < row.length) {
			const char = row[x];
			if (char === '.' || !PALETTE[char]) {
				x++;
				continue;
			}
			let width = 1;
			while (row[x + width] === char) width++;
			rects.push({ x, y, w: width, fill: PALETTE[char] });
			x += width;
		}
	});

	return rects;
}
